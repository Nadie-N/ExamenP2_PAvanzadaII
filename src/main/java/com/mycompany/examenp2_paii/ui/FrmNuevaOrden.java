    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed

        try {
            // 1. Validaciones
            if (cmbCliente.getSelectedIndex() == -1 || cmbVehiculo.getSelectedIndex() == -1) {
                JOptionPane.showMessageDialog(this, "Debe seleccionar cliente y vehículo.");
                return;
            }

            // 2. Armar el objeto
            OrdenTrabajo o = new OrdenTrabajo();
            o.setIdCliente(((Cliente)cmbCliente.getSelectedItem()).getIdCliente());
            o.setIdVehiculo(((Vehiculo)cmbVehiculo.getSelectedItem()).getIdVehiculo());

            if (cmbMecanico.getSelectedIndex() != -1) {
                o.setIdMecanicoResponsable(((Mecanico)cmbMecanico.getSelectedItem()).getIdMecanico());
            }

            o.setKilometraje(Integer.parseInt(txtKilometraje.getText()));
            o.setSintomas(txtSintomas.getText());

            // 3. Guardar en BD
            OrdenDAO dao = new OrdenDAO();
            int idGenerado = dao.insertarOrden(o);

            JOptionPane.showMessageDialog(this, "Orden creada con éxito. ID: " + idGenerado);
            this.dispose(); 

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "El kilometraje debe ser un número.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error de BD: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnCrearActionPerformed

    private void cmbClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbClienteActionPerformed
                                              
        cmbVehiculo.removeAllItems(); 
        
        Cliente seleccionado = (Cliente) cmbCliente.getSelectedItem();
        if (seleccionado != null) {
            com.mycompany.examenp2_paii.dao.VehiculoDAO vDao = new com.mycompany.examenp2_paii.dao.VehiculoDAO();
            java.util.List<Vehiculo> vehiculos = vDao.listarPorCliente(seleccionado.getIdCliente());
            for (Vehiculo v : vehiculos) {
                cmbVehiculo.addItem(v);
            }
        }
    
    }//GEN-LAST:event_cmbClienteActionPerformed

