    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
                                         
        try {
            // 1. Validaciones básicas
            if (txtIdOrden.getText().trim().isEmpty() || cmbMotor.getSelectedItem() == null) {
                JOptionPane.showMessageDialog(this, "Debe ingresar el ID de la orden y seleccionar un motor.");
                return;
            }
            if (!chkAutorizacion.isSelected()) {
                JOptionPane.showMessageDialog(this, "El cliente debe autorizar el cambio para continuar.");
                return;
            }

            // 2. Extraer el ID de la Orden desde el TextField
            int idOrden = Integer.parseInt(txtIdOrden.getText().trim());

            // 3. Extraer el ID y la Serie del Motor del ComboBox
            String motorSeleccionado = cmbMotor.getSelectedItem().toString();
            String[] partesMotor = motorSeleccionado.split(" - ");
            int idMotor = Integer.parseInt(partesMotor[0].trim()); 
            String serieNueva = partesMotor[1].trim();             

            // 4. Extraer los datos de los TextFields
            String serieAnterior = txtSerieAnterior.getText().trim();
            String destino = txtDestino.getText().trim();
            double manoObra = Double.parseDouble(txtManoObra.getText().trim());
            int garantia = Integer.parseInt(txtGarantia.getText().trim());

            // 5. Llamar al DAO
            CambioMotorDAO dao = new CambioMotorDAO();
            boolean exito = dao.registrarCambioMotor(idOrden, idMotor, serieAnterior, serieNueva, manoObra, true, destino, garantia);

            if (exito) {
                JOptionPane.showMessageDialog(this, "¡Éxito! Motor cambiado, garantía generada y control de calidad aprobado.");
                this.dispose(); 
            }

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Verifique los campos numéricos (ID Orden, Mano de obra y Garantía).");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error de Base de Datos: " + ex.getMessage());
        }
     
    }//GEN-LAST:event_btnRegistrarActionPerformed

