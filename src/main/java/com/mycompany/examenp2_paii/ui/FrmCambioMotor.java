    private void cargarMotores() {
        // Cargar Motores Disponibles en el cmbMotor
        try (Connection conn = DatabaseConnection.getConnection();
             Statement st = conn.createStatement();
             ResultSet rs = st.executeQuery("SELECT IdMotor, NumeroSerie FROM Motores WHERE Estado = 'Disponible'")) {
            
            cmbMotor.removeAllItems(); // Limpiamos el ComboBox por defecto
            while (rs.next()) {
                // Mostrará en el cmbMotor: "1 - MOT-HILUX-001"
                cmbMotor.addItem(rs.getInt("IdMotor") + " - " + rs.getString("NumeroSerie"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar motores: " + e.getMessage());
        }
    }
