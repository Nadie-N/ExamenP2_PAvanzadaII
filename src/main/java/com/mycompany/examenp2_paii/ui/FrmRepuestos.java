    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
                                             
        try {
            com.mycompany.examenp2_paii.model.Repuesto r = new com.mycompany.examenp2_paii.model.Repuesto();
            r.setCodigo(txtCodigo.getText().trim());
            r.setNombre(txtNombre.getText().trim());
            r.setCosto(Double.parseDouble(txtCosto.getText().trim()));
            r.setPrecioVenta(Double.parseDouble(txtPrecio.getText().trim()));
            r.setStock(Integer.parseInt(txtStock.getText().trim()));
            r.setStockMinimo(Integer.parseInt(txtStockMin.getText().trim()));

            com.mycompany.examenp2_paii.dao.RepuestoDAO dao = new com.mycompany.examenp2_paii.dao.RepuestoDAO();
            dao.insertarRepuesto(r);
            
            javax.swing.JOptionPane.showMessageDialog(this, "¡Repuesto guardado con éxito!");
            
            // Limpiar
            txtCodigo.setText(""); txtNombre.setText(""); txtCosto.setText(""); 
            txtPrecio.setText(""); txtStock.setText(""); txtStockMin.setText("");
            
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Verifique que Costo, Precio y Stock sean números.");
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
     
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnConsumirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsumirActionPerformed
                                       
        try {
            int idOrden = Integer.parseInt(txtIdOrden.getText().trim());
            int idRepuesto = Integer.parseInt(txtIdRepuesto.getText().trim());
            int cantidad = Integer.parseInt(txtCantidad.getText().trim());

            com.mycompany.examenp2_paii.dao.RepuestoDAO dao = new com.mycompany.examenp2_paii.dao.RepuestoDAO();
            
            // Este es el método transaccional que creamos en el DAO
            dao.consumirRepuesto(idOrden, idRepuesto, cantidad);
            
            javax.swing.JOptionPane.showMessageDialog(this, "¡Consumo registrado y stock descontado!");
            txtIdOrden.setText(""); txtIdRepuesto.setText(""); txtCantidad.setText("");
            
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Los IDs y la cantidad deben ser números.");
        } catch (java.sql.SQLException ex) {
            // Aquí saldrá el error si no hay stock suficiente (Rollback)
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Error de Transacción", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    
    }//GEN-LAST:event_btnConsumirActionPerformed

